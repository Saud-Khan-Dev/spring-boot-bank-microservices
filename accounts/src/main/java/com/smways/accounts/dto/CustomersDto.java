package com.smways.accounts.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@AllArgsConstructor
@NoArgsConstructor
@Schema(
    name = "Customer",
    description = "Schema to hold Customer and Account information"
)
public class CustomersDto {

    @Schema(description = "Unique id of the customer, generated by the server", example = "1",
        accessMode = Schema.AccessMode.READ_ONLY)
    private Long customerId;

    @Schema(description = "Full name of the customer", example = "Saud Khan")
    @NotEmpty(message = "Customer name cannot be empty")
    @Size (min = 5, max = 30, message = "Customer name must be between 5 and 30 characters")
    private String name;

    @Schema(description = "Email address of the customer", example = "saud@example.com")
    @NotEmpty (message = "Email cannot be empty")
    @Email (message = "Email should be valid")
    private String email;

    @Schema(description = "10 digit mobile number of the customer", example = "9876543210")
    @Pattern (regexp = "^[0-9]{10}$", message = "Mobile number must be 10 digits")
    @NotEmpty (message = "Mobile number cannot be empty")
    @Size (min = 10, max = 10, message = "Mobile number must be 10 digits")
    private String mobileNumber;

    @Schema(description = "Account details of the customer. Required for update, ignored for create")
    private AccountsDto accountsDto;
}
